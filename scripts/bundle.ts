// Builds the committed single-file bundles: the GitHub Action and the Claude Code plugin script.
// Run with `npm run bundle`; tests/bundle.test.ts fails when a committed bundle is out of date.
import { chmodSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { rolldown } from 'rolldown';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export interface BundleSpec {
  /** Source entry, relative to the repo root. */
  readonly input: string;
  /** Committed output, relative to the repo root. */
  readonly output: string;
  /** Whether the output is run directly (a shebang and the executable bit). */
  readonly executable: boolean;
}

export const BUNDLES: readonly BundleSpec[] = [
  { input: 'src/action/index.ts', output: 'action/dist/index.mjs', executable: false },
  { input: 'src/plugin/index.ts', output: 'plugin/scripts/guard.mjs', executable: true },
];

const NOTICE = '// Generated by `npm run bundle` from the TypeScript sources in src/. Do not edit.';

/** Bundles one entry into a single ESM file, unminified so the committed code can be audited. */
export async function bundleCode(spec: BundleSpec): Promise<string> {
  const build = await rolldown({
    input: join(ROOT, spec.input),
    platform: 'node',
    resolve: { extensionAlias: { '.js': ['.ts', '.js'] } },
    logLevel: 'warn',
  });
  try {
    const { output } = await build.generate({
      format: 'esm',
      banner: spec.executable ? `#!/usr/bin/env node\n${NOTICE}` : NOTICE,
      sourcemap: false,
      minify: false,
      codeSplitting: false,
    });
    const [chunk, ...rest] = output;
    if (chunk === undefined || chunk.type !== 'chunk' || rest.length > 0) throw new Error(`${spec.input} did not bundle into exactly one file`);
    return chunk.code;
  } finally {
    await build.close();
  }
}

export async function writeBundles(): Promise<void> {
  for (const spec of BUNDLES) {
    const path = join(ROOT, spec.output);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, await bundleCode(spec), 'utf8');
    if (spec.executable) chmodSync(path, 0o755);
    process.stdout.write(`wrote ${spec.output}\n`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await writeBundles();
